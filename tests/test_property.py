"""Replayable property regressions for the archive search contract.

The oracle in ``property_oracle`` derives paragraphs, line numbers, digests
and expected hit sets from raw bytes on its own.  It never imports the
product to build expectations; every comparison crosses that boundary.

A failure writes a self-contained bundle under ``run/property-failures``
(or ``ARCHIVE_PROPERTY_FAILURE_DIR``) holding the corpus, manifest, seed,
query and one replay command.
"""
import hashlib
import json
import os
from pathlib import Path
import sqlite3
import subprocess
import sys
import tempfile
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parent))

import property_oracle as oracle  # noqa: E402

from archive_index.query import search  # noqa: E402
from archive_index.store import build  # noqa: E402

REPO_ROOT = oracle.REPO_ROOT


def result_key_list(hits):
    return [(hit['document_id'], hit['paragraph']) for hit in hits]


class PropertyTests(unittest.TestCase):
    """Every seed is built once; queries are compared against the oracle."""

    @classmethod
    def setUpClass(cls):
        cls.temporary = tempfile.TemporaryDirectory()
        cls.addClassCleanup(cls.temporary.cleanup)
        cls.built = {}
        for seed in oracle.SEEDS:
            corpus = oracle.build_corpus(seed)
            root = Path(cls.temporary.name) / f'seed-{seed}'
            oracle.write_corpus(root, corpus)
            database = root / 'archive.sqlite'
            result = build(root / 'manifest.json', database)
            rows = oracle.derive_rows(oracle.corpus_from_directory(root))
            cls.built[seed] = {
                'corpus': corpus, 'root': root, 'database': database,
                'rows': rows, 'summary': result,
                'queries': oracle.query_bank(seed, corpus),
            }

    # -- helpers ----------------------------------------------------------
    def corpus_context(self, seed):
        entry = self.built[seed]
        return entry['corpus'], entry['rows'], entry['database']

    def fail_case(self, test, seed, query, collection=None, limit=None,
                  detail=None, via_cli=False, mode='search'):
        corpus = self.built[seed]['corpus']
        case, command = oracle.write_failure_bundle(
            test, corpus, query, collection, limit, via_cli, detail,
            mode=mode)
        self.fail(f'{test} failed for seed {seed}, query {query!r}, '
                  f'collection {collection!r}: {detail}\n'
                  f'failure bundle: {case}\nreplay: {command}')

    # -- corpus invariants ------------------------------------------------
    def test_corpus_shape_and_features(self):
        for seed in oracle.SEEDS:
            entry = self.built[seed]
            rows, corpus = entry['rows'], entry['corpus']
            with self.subTest(seed=seed):
                self.assertEqual(entry['summary']['documents'],
                                 len(corpus['documents']))
                self.assertEqual(entry['summary']['paragraphs'], len(rows))
                self.assertGreaterEqual(len(rows), 15)
                self.assertGreaterEqual(
                    len({row['collection'] for row in rows}), 3)
                # Duplicate whole bodies under identical titles.
                bodies = [document['raw'] for document in corpus['documents']]
                self.assertTrue(any(bodies.count(raw) > 1 for raw in bodies))
                # A paragraph repeated inside one document.
                self.assertTrue(any(
                    [text for _, _, text in life].count(body) > 1
                    for life in (oracle.raw_paragraphs(document['raw'])
                                 for document in corpus['documents'])
                    for _, _, body in life))
                # A paragraph duplicated across two different documents.
                all_texts = [row['text'] for row in rows]
                self.assertTrue(any(row['text'] in all_texts for row in rows
                                    if all_texts.count(row['text']) > 1))
                # CRLF present in at least one document.
                self.assertTrue(any(b'\r\n' in raw for raw in bodies))
                # Blank lines and whitespace-only separators present.
                self.assertTrue(any(b'\n\n' in raw for raw in bodies))
                self.assertTrue(any(b'\r\n\t \t\r\n' in raw for raw in bodies))
                # Every title-only term is absent from all bodies.
                for word in oracle.TITLE_ONLY:
                    self.assertTrue(any(word in row['title_tokens']
                                        for row in rows))
                    self.assertFalse(any(word in row['body_tokens']
                                         for row in rows))
                # The saved bytes on disk are exactly the generated bytes.
                for document in corpus['documents']:
                    self.assertEqual(
                        hashlib.sha256(document['raw']).hexdigest(),
                        hashlib.sha256((entry['root'] / document['path'])
                                       .read_bytes()).hexdigest())

    def test_manifest_order_does_not_change_hits(self):
        for seed in oracle.SEEDS:
            entry = self.built[seed]
            corpus, rows, database = self.corpus_context(seed)
            with self.subTest(seed=seed):
                other = Path(self.temporary.name) / f'seed-{seed}-reordered'
                identifiers = [document['id'] for document in corpus['documents']]
                reversed_ids = list(reversed(identifiers))
                oracle.write_corpus(other, corpus, order=reversed_ids)
                other_db = other / 'archive.sqlite'
                summary = build(other / 'manifest.json', other_db)
                self.assertEqual(summary['paragraphs'], entry['summary']['paragraphs'])
                for query in entry['queries']:
                    hits = search(database, query, limit=100)
                    reordered = search(other_db, query, limit=100)
                    if result_key_list(hits) != result_key_list(reordered):
                        self.fail_case(
                            'manifest-reordering', seed, query,
                            detail=f'{result_key_list(hits)} != '
                                   f'{result_key_list(reordered)}',
                            mode='reorder')
                    # text and citation fields are order-independent too
                    actual_fields = [(h['document_id'], h['paragraph'],
                                      h['start_line'], h['end_line'], h['text'])
                                     for h in hits]
                    other_fields = [(h['document_id'], h['paragraph'],
                                     h['start_line'], h['end_line'], h['text'])
                                    for h in reordered]
                    if actual_fields != other_fields:
                        self.fail_case('manifest-reordering-fields', seed, query,
                                       detail=f'{actual_fields} != {other_fields}',
                                       mode='reorder')

    # -- oracle agreement -------------------------------------------------
    def test_hits_match_reference_for_every_query(self):
        for seed in oracle.SEEDS:
            corpus, rows, database = self.corpus_context(seed)
            for query in self.built[seed]['queries']:
                with self.subTest(seed=seed, query=query):
                    hits = search(database, query, limit=100)
                    issues = oracle.check_hits(hits, rows, query)
                    if issues:
                        self.fail_case('reference-hits', seed, query,
                                       detail='; '.join(issues))
                    self.assertEqual(len(hits),
                                     len(oracle.expected_hits(rows, query)))

    def test_collection_filter_is_exact(self):
        for seed in oracle.SEEDS:
            corpus, rows, database = self.corpus_context(seed)
            collections = sorted({row['collection'] for row in rows})
            queries = ('harbor', 'copper', 'zephyr', 'restoration',
                       '(harbor OR copper)', 'absentword')
            for query in queries:
                for collection in collections + ['Engineering', 'absent']:
                    with self.subTest(seed=seed, query=query,
                                      collection=collection):
                        hits = search(database, query, collection=collection,
                                      limit=100)
                        # case-sensitive exact equality: 'Engineering' is a
                        # different value from 'engineering'
                        self.assertTrue(all(h['collection'] == collection
                                            for h in hits))
                        issues = oracle.check_hits(hits, rows, query,
                                                   collection)
                        if issues:
                            self.fail_case('collection-filter', seed, query,
                                           collection, detail='; '.join(issues))

    def test_limit_truncates_a_stable_prefix(self):
        for seed in oracle.SEEDS:
            corpus, rows, database = self.corpus_context(seed)
            for query in ('harbor', 'copper', 'shared',
                          '"shared bulletin"', '(harbor OR tide)'):
                with self.subTest(seed=seed, query=query):
                    full = search(database, query, limit=100)
                    for limit in (1, 2, 3, 5):
                        cut = search(database, query, limit=limit)
                        self.assertEqual(result_key_list(cut),
                                         result_key_list(full[:limit]))
                        self.assertLessEqual(len(cut), limit)
                        # Truncation is against the ranked prefix, not the
                        # complete reference set; the prefix must still be
                        # reference-consistent.
                        issues = oracle.check_hits(cut, rows, query,
                                                   expect_complete=False)
                        if issues:
                            self.fail_case('limit', seed, query, limit=limit,
                                           detail='; '.join(issues),
                                           mode='limit')

    def test_ordering_and_ties_are_stable(self):
        for seed in oracle.SEEDS:
            corpus, rows, database = self.corpus_context(seed)
            for query in ('shared', '"shared bulletin"', 'meridian',
                          'repeated', '"repeated note"', 'copper'):
                with self.subTest(seed=seed, query=query):
                    hits = search(database, query, limit=100)
                    issues = oracle.ordering_issues(hits)
                    if issues:
                        self.fail_case('ordering', seed, query,
                                       detail='; '.join(issues), mode='order')
                    # Repeated runs must be identical.
                    again = search(database, query, limit=100)
                    if result_key_list(again) != result_key_list(hits):
                        self.fail_case('repeat-run', seed, query,
                                       detail=f'{result_key_list(hits)} != '
                                              f'{result_key_list(again)}',
                                       mode='order')
                    by_key = {(h['document_id'], h['paragraph']): h
                              for h in hits}
                    # Queries that reach D04/D05 must return both paragraphs
                    # with equal ranks because the two documents are
                    # byte-identical; queries that do not reach them must
                    # return neither.
                    expected_keys = set(oracle.expected_key_list(rows, query))
                    for paragraph in (1, 2):
                        wanted = {('D04', paragraph), ('D05', paragraph)}
                        present = wanted & set(by_key)
                        if present != wanted & expected_keys:
                            self.fail_case(
                                'identical-documents-presence', seed, query,
                                detail=f'{sorted(present)} vs '
                                       f'{sorted(wanted & expected_keys)}',
                                mode='order')
                        if present == wanted:
                            left, right = (by_key[('D04', paragraph)],
                                           by_key[('D05', paragraph)])
                            if left['rank'] != right['rank'] or \
                                    left['text'] != right['text']:
                                self.fail_case(
                                    'identical-documents', seed, query,
                                    detail=f'D04/D05 paragraph {paragraph}: '
                                           f'{left["rank"]}/{left["text"]!r} vs '
                                           f'{right["rank"]}/{right["text"]!r}',
                                    mode='order')
                    # D06 repeats one body in paragraphs 1 and 2; whenever the
                    # query reaches them, equal text must tie and the lower
                    # paragraph number sorts first.
                    if {('D06', 1), ('D06', 2)} <= set(by_key):
                        first = by_key[('D06', 1)]
                        second = by_key[('D06', 2)]
                        if first['rank'] != second['rank']:
                            self.fail_case(
                                'duplicate-paragraph-rank', seed, query,
                                detail=f'{first["rank"]} != {second["rank"]}',
                                mode='order')
                        if result_key_list(hits).index(('D06', 1)) > \
                                result_key_list(hits).index(('D06', 2)):
                            self.fail_case('duplicate-paragraph-order', seed,
                                           query, detail='D06 1 after 2',
                                           mode='order')

    def test_rebuild_and_reorder_are_logically_identical(self):
        for seed in oracle.SEEDS:
            entry = self.built[seed]
            corpus, rows, database = self.corpus_context(seed)
            with self.subTest(seed=seed):
                rebuilt = Path(self.temporary.name) / f'seed-{seed}-rebuilt.sqlite'
                build(entry['root'] / 'manifest.json', rebuilt)
                for query in entry['queries']:
                    if result_key_list(search(database, query, limit=100)) != \
                            result_key_list(search(rebuilt, query, limit=100)):
                        self.fail_case('rebuild', seed, query, mode='rebuild')

    # -- real CLI ---------------------------------------------------------
    def test_cli_matches_library_and_oracle(self):
        env = dict(os.environ, PYTHONPATH=str(REPO_ROOT / 'src'))
        for seed in oracle.SEEDS:
            corpus, rows, database = self.corpus_context(seed)
            with self.subTest(seed=seed):
                for query in ('harbor', 'zephyr', '"shared bulletin"',
                              '(harbor OR copper) AND tide', 'absentword'):
                    command = [sys.executable, '-m', 'archive_index.cli',
                               'search', '--database', str(database),
                               '--query', query, '--limit', '100']
                    completed = subprocess.run(command, capture_output=True,
                                               text=True, cwd=REPO_ROOT,
                                               env=env)
                    if completed.returncode != 0:
                        self.fail_case('cli-exit', seed, query, via_cli=True,
                                       detail=completed.stderr.strip())
                    matches = json.loads(completed.stdout)['matches']
                    reference = search(database, query, limit=100)
                    if result_key_list(matches) != result_key_list(reference):
                        self.fail_case('cli-vs-library', seed, query,
                                       via_cli=True)
                    issues = oracle.check_hits(matches, rows, query)
                    if issues:
                        self.fail_case('cli-vs-oracle', seed, query,
                                       via_cli=True, detail='; '.join(issues))
                    # A filtered CLI search agrees as well.
                    filtered = subprocess.run(
                        command + ['--collection', 'engineering'],
                        capture_output=True, text=True, cwd=REPO_ROOT,
                        env=env)
                    if filtered.returncode != 0:
                        self.fail_case('cli-filter-exit', seed, query,
                                       collection='engineering', via_cli=True,
                                       detail=filtered.stderr.strip())
                    filtered_hits = json.loads(filtered.stdout)['matches']
                    issues = oracle.check_hits(filtered_hits, rows, query,
                                               'engineering')
                    if issues:
                        self.fail_case('cli-filter', seed, query,
                                       collection='engineering', via_cli=True,
                                       detail='; '.join(issues))

    def test_cli_build_of_generated_corpus(self):
        env = dict(os.environ, PYTHONPATH=str(REPO_ROOT / 'src'))
        for seed in oracle.SEEDS:
            entry = self.built[seed]
            target = Path(self.temporary.name) / f'seed-{seed}-cli.sqlite'
            command = [sys.executable, '-m', 'archive_index.cli', 'build',
                       '--manifest', str(entry['root'] / 'manifest.json'),
                       '--database', str(target)]
            completed = subprocess.run(command, capture_output=True, text=True,
                                       cwd=REPO_ROOT, env=env)
            with self.subTest(seed=seed):
                if completed.returncode != 0:
                    self.fail_case('cli-build', seed, None, via_cli=True,
                                   detail=completed.stderr.strip(),
                                   mode='build')
                summary = json.loads(completed.stdout)
                self.assertEqual(summary['paragraphs'],
                                 entry['summary']['paragraphs'])
                with sqlite3.connect(target) as connection:
                    self.assertEqual(
                        connection.execute('PRAGMA integrity_check')
                        .fetchone()[0], 'ok')

    # -- failure bundles --------------------------------------------------
    def test_failure_bundle_is_self_contained(self):
        corpus = oracle.build_corpus(oracle.SEEDS[0])
        with tempfile.TemporaryDirectory() as temporary:
            case, command = oracle.write_failure_bundle(
                'bundle-self-check', corpus, 'harbor NOT copper',
                'engineering', 5, detail='deliberate self-check',
                root=Path(temporary))
            files = {path.name for path in case.iterdir()}
            self.assertLessEqual(
                {'manifest.json', 'seed.txt', 'request.json', 'query.txt',
                 'replay.sh', 'README.txt'}, files)
            self.assertIn('D01', (case / 'manifest.json').read_text())
            self.assertEqual((case / 'query.txt').read_text(),
                             'harbor NOT copper\n')
            self.assertEqual(int((case / 'seed.txt').read_text()),
                             oracle.SEEDS[0])
            replayed = oracle.corpus_from_directory(case)
            # The bundle alone still reproduces the corpus and reference hits.
            self.assertEqual(
                replayed['manifest'], corpus['manifest'])
            for document, original in zip(
                    sorted(replayed['documents'], key=lambda d: d['id']),
                    sorted(corpus['documents'], key=lambda d: d['id'])):
                self.assertEqual(document['raw'], original['raw'])
            rows = oracle.derive_rows(replayed)
            expected = set(oracle.expected_key_list(
                rows, 'harbor NOT copper', 'engineering'))
            self.assertTrue(expected)
            self.assertIn('PYTHONPATH=src', command)
            self.assertIn(str(case), command)


if __name__ == '__main__':
    unittest.main(verbosity=2)
